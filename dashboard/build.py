"""Build the static analytics dashboard from a gold Parquet export (ticket #29).

    python -m dashboard.build --gold data/gold --out site/

Pipeline: gold Parquet -> dbt marts on a throwaway DuckDB file (``dbt run``, no tests; the dbt
workflow already tests them) -> the analyst queries in ``analytics/queries/`` plus the
dashboard-specific ones in ``dashboard/queries/`` -> one JSON payload -> ``site/index.html``
with CSS, JS and the data inlined. The page makes no network requests. All data is synthetic.

Pass ``--marts-db`` to reuse marts that were already built (skips dbt, e.g. when CI built them
for the dbt job). Optional inputs for the data-quality view: ``--raw`` (claimsgen output with
``defects_manifest.json``), ``--reconciliation`` and ``--quality-json`` (see ``quality.py``).
"""

from __future__ import annotations

import argparse
import datetime as dt
import decimal
import importlib.util
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from dashboard import metrics, quality

ROOT = Path(__file__).resolve().parents[1]
HERE = Path(__file__).resolve().parent
QUERY_DIRS = [ROOT / "analytics" / "queries", HERE / "queries"]
# Every view the member-cost-concentration section declares; app.js must render each one.
MEMBER_VIEWS = ("lorenz", "pareto", "risk_tiers")
PARETO_SLICES = (1, 5, 10, 20, 50)
SYNTHETIC_NOTICE = (
    "All data is synthetic, generated by code in this repository. "
    "No real patients, providers or payers."
)


def _load_runner():
    """Import scripts/run_analytics_queries.py so the dashboard obeys the same query contract."""
    spec = importlib.util.spec_from_file_location(
        "run_analytics_queries", ROOT / "scripts" / "run_analytics_queries.py"
    )
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def resolve_gold(path: Path) -> Path:
    """Accept a gold root (``<root>/export/<table>``) or the export dir itself."""
    if (path / "export" / "fact_claim").is_dir():
        return path / "export"
    if (path / "fact_claim").is_dir():
        return path
    raise SystemExit(f"error: no fact_claim/ under {path} (or {path}/export); is this a gold root?")


def build_marts(gold: Path, db: Path, workdir: Path) -> None:
    """Run ``dbt run`` (models only) on the gold export into ``db``.

    Uses a temporary profiles dir and target/log paths so the repo working tree stays clean.
    """
    profiles = workdir / "profiles"
    profiles.mkdir(parents=True, exist_ok=True)
    shutil.copy(ROOT / "dbt" / "profiles.yml.example", profiles / "profiles.yml")
    env = {
        **os.environ,
        "DBT_PROFILES_DIR": str(profiles),
        "DBT_DUCKDB_PATH": str(db),
        "DBT_TARGET_PATH": str(workdir / "target"),
        "DBT_LOG_PATH": str(workdir / "logs"),
        "DBT_SEND_ANONYMOUS_USAGE_STATS": "False",
    }
    base = [sys.executable, "-c", "from dbt.cli.main import cli; cli()"]
    common = ["--project-dir", str(ROOT / "dbt"), "--target", "duckdb"]
    if not (ROOT / "dbt" / "dbt_packages").is_dir():
        subprocess.run([*base, "deps", "--project-dir", str(ROOT / "dbt")], check=True, env=env)
    subprocess.run(
        [*base, "run", *common, "--vars", json.dumps({"gold_path": str(gold)})],
        check=True,
        env=env,
        stdout=subprocess.DEVNULL,
    )


def _jsonable(v):
    if isinstance(v, decimal.Decimal):
        return float(v)
    if isinstance(v, dt.date | dt.datetime):
        return v.isoformat()
    return v


def run_queries(con, runner) -> dict[str, dict]:
    """Execute every query file under the contract checks; return header + rows per file."""
    out: dict[str, dict] = {}
    for qdir in QUERY_DIRS:
        for path in sorted(qdir.glob("*.sql")):
            runner.run_query(con, path)  # raises QueryError if the contract is violated
            text = path.read_text()
            header = runner.parse_header(text)
            cur = con.execute(runner.sql_body(text))
            cols = [d[0] for d in cur.description]
            out[path.stem] = {
                "file": f"{qdir.relative_to(ROOT).as_posix()}/{path.name}",
                "question": header["question"],
                "grain": header["grain"],
                "caveat": header["caveat"],
                "columns": cols,
                "rows": [dict(zip(cols, map(_jsonable, r), strict=True)) for r in cur.fetchall()],
            }
    return out


def _with_ci(rows: list[dict], n_key: str, k_key: str) -> list[dict]:
    """Attach a 95 percent Wilson interval to each row's denial rate."""
    for r in rows:
        lo, hi = metrics.wilson_interval(int(r[k_key]), int(r[n_key]))
        r["ci_low"], r["ci_high"] = round(lo, 4), round(hi, 4)
    return rows


def assemble(queries: dict[str, dict], qual: dict, gold: Path, gold_label: str) -> dict:
    """Combine query results and quality inputs into the single payload the page renders."""
    q = {k: v["rows"] for k, v in queries.items()}
    monthly = q["d01_monthly_cost_and_denials"]
    claims = sum(r["claim_count"] for r in monthly)
    denied = sum(r["denied_claim_count"] for r in monthly)
    billed = sum(r["billed_amount"] for r in monthly)
    allowed = sum(r["allowed_amount"] for r in monthly)
    paid = sum(r["paid_amount"] for r in monthly)
    pmpm = [r["pmpm_paid"] for r in monthly]
    trend = metrics.linear_trend(pmpm)

    lorenz_pts = [
        (r["members_pct"] / 100, r["cum_paid_share"]) for r in q["d04_member_cost_lorenz"]
    ]
    lorenz_pts = [(0.0, 0.0), *lorenz_pts]
    conc = {
        "gini": metrics.gini_from_lorenz(lorenz_pts),
        **{f"top{p}": metrics.top_share(lorenz_pts, p) for p in PARETO_SLICES},
        "members": q["d04_member_cost_lorenz"][-1]["cum_member_count"],
    }

    peers = q["d03_provider_peer_index"]
    flagged = q["09_outlier_providers_vs_specialty"]
    tiers: dict[str, dict[str, int]] = {}
    flagged_ids = {r["provider_id"] for r in flagged}
    for r in peers:
        t = tiers.setdefault(r["cost_tier"], {"providers": 0, "flagged": 0})
        t["providers"] += 1
        t["flagged"] += r["provider_id"] in flagged_ids

    return {
        "meta": {
            "title": "Claims lakehouse analytics",
            "synthetic_notice": SYNTHETIC_NOTICE,
            "gold_source": gold_label,
            "gold_dir": gold.name,
            "period": [monthly[0]["service_month"], monthly[-1]["service_month"]],
            "queries": {
                k: {"file": v["file"], "question": v["question"]} for k, v in queries.items()
            },
            "caveats": {k: v["caveat"] for k, v in queries.items()},
        },
        "kpis": {
            "claims": claims,
            "denied_claims": denied,
            "denial_rate": denied / claims,
            "billed": billed,
            "allowed": allowed,
            "paid": paid,
            "paid_to_billed": paid / billed,
            "pmpm_latest": pmpm[-1],
            "pmpm_first": pmpm[0],
            "members": conc["members"],
            "providers": len({r["provider_id"] for r in q["02_top_providers_by_allowed"]}),
        },
        "monthly": monthly,
        "pmpm_trend": {k: trend[k] for k in ("slope", "intercept", "r2", "fitted")},
        "claim_type_mix": q["07_claim_type_cost_mix"],
        "denials": {
            "by_claim_type": _with_ci(
                q["03_denial_rate_by_claim_type"], "claim_count", "denied_claim_count"
            ),
            "by_specialty": _with_ci(
                q["d02_denials_by_specialty"], "claim_count", "denied_claim_count"
            ),
            "by_plan_type": _with_ci(
                q["04_denial_rate_by_plan_type"], "claim_count", "denied_claim_count"
            ),
            "has_reason_or_payer": False,
        },
        "providers": {
            "peer_index": peers,
            "flagged": flagged,
            "specialty_benchmark": q["06_specialty_benchmark"],
            "tier_summary": tiers,
            "flag_threshold": 1.25,
            "min_claims": 20,
        },
        "members": {
            "views": list(MEMBER_VIEWS),
            "lorenz": [{"x": x, "y": y} for x, y in lorenz_pts],
            "concentration": conc,
            "pareto": [
                {"top_pct": p, "share": metrics.top_share(lorenz_pts, p)} for p in PARETO_SLICES
            ],
            "risk_tiers": q["05_high_cost_member_cohort"],
        },
        "quality": qual,
    }


def quality_section(
    gold: Path,
    raw: Path | None,
    reconciliation: Path | None,
    quality_json: Path | None,
) -> dict:
    import duckdb

    con = duckdb.connect()
    invariants = quality.gold_invariants(con, gold)
    manifest = quality.load_manifest(raw) if raw else None
    return {
        "invariants": invariants,
        "defects": quality.defect_catch_table(manifest, invariants) if manifest else None,
        "defects_note": None
        if manifest
        else "No defects_manifest.json supplied (--raw); catch rates are not shown.",
        "raw_to_gold": quality.raw_to_gold_counts(con, raw, gold) if manifest else None,
        "reconciliation": quality.load_reconciliation(reconciliation),
        "quality_framework": quality.load_quality_json(quality_json),
        "manifest_seed": manifest.get("seed") if manifest else None,
        "manifest_claims": manifest.get("claims") if manifest else None,
    }


def render(payload: dict) -> str:
    """Inline CSS, JS and data into the HTML template. Output has no external references."""
    tpl = (HERE / "template.html").read_text()
    data = json.dumps(payload, separators=(",", ":"), allow_nan=False).replace("</", "<\\/")
    return (
        tpl.replace("/*__CSS__*/", (HERE / "style.css").read_text())
        .replace("/*__JS__*/", (HERE / "app.js").read_text())
        .replace("__DATA__", data)
    )


def build(
    gold: Path,
    out: Path,
    marts_db: Path | None = None,
    raw: Path | None = None,
    reconciliation: Path | None = None,
    quality_json: Path | None = None,
    gold_label: str = "gold-shaped test fixture",
) -> Path:
    import duckdb

    gold = resolve_gold(gold.resolve())
    with tempfile.TemporaryDirectory(prefix="dashboard-") as tmp:
        work = Path(tmp)
        db = (
            marts_db.resolve() if marts_db else work / "claims.duckdb"
        )  # 'claims' != schema 'marts'
        if not marts_db:
            build_marts(gold, db, work)
        con = duckdb.connect(str(db), read_only=True)
        queries = run_queries(con, _load_runner())
        con.close()
    qual = quality_section(gold, raw, reconciliation, quality_json)
    payload = assemble(queries, qual, gold, gold_label)
    out.mkdir(parents=True, exist_ok=True)
    target = out / "index.html"
    target.write_text(render(payload), encoding="utf-8")
    return target


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--gold", type=Path, required=True, help="gold root or its export/ dir")
    ap.add_argument("--out", type=Path, default=Path("site"), help="output dir (default site/)")
    ap.add_argument("--marts-db", type=Path, help="prebuilt DuckDB with marts.mart_* (skips dbt)")
    ap.add_argument("--raw", type=Path, help="claimsgen output root (defects_manifest.json)")
    ap.add_argument(
        "--reconciliation", type=Path, help="exported gold_reconciliation (.json/.parquet)"
    )
    ap.add_argument("--quality-json", type=Path, help="data-quality framework summary (#22)")
    ap.add_argument(
        "--gold-label",
        default="gold-shaped test fixture",
        help="how the page describes the source (e.g. 'Spark gold export')",
    )
    a = ap.parse_args(argv)
    target = build(a.gold, a.out, a.marts_db, a.raw, a.reconciliation, a.quality_json, a.gold_label)
    print(f"wrote {target} ({target.stat().st_size / 1024:.0f} KiB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
